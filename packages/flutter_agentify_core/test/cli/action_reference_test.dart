import 'package:flutter_agentify_core/flutter_agentify_core.dart';
import 'package:test/test.dart';

import '../actions/fake_action.dart';

class _Typed extends AgentAction<(String, int?), String> {
  @override
  String get name => 'add_item';

  @override
  String get description => 'Adds an item to the list.';

  @override
  ObjectSchema<(String, int?)> get input => S.object(
    fields: {
      'title': S.string(description: 'What to add.', minLength: 1),
      'count': S.integer(description: 'How many.', min: 1).optional(),
      'tags': S
          .list(S.string(description: 'A tag.'), description: 'Labels.')
          .optional(),
    },
    build: (v) => (v['title'] as String, v['count'] as int?),
  );

  @override
  List<String> get resources => const ['items'];

  @override
  List<String> get failureCodes => const ['duplicate'];

  @override
  Future<String> run((String, int?) input, ActionContext context) async => 'ok';

  @override
  Object? encode(String output) => output;
}

void main() {
  test('the reference is deterministic and sorted by name', () {
    final a = buildActionReference(ActionRegistry([wipe(), echo(), _Typed()]));
    final b = buildActionReference(ActionRegistry([_Typed(), echo(), wipe()]));
    expect(a, b);
    expect(
      a,
      startsWith(
        '<!-- Generated by tool/action.dart --write-reference. Do not edit. -->\n',
      ),
    );
    final order = ['## add_item', '## echo', '## wipe'].map(a.indexOf).toList();
    expect(order, everyElement(greaterThan(0)));
    expect(order, orderedEquals([...order]..sort()));
  });

  test('it lists flags, fields and failure codes', () {
    final text = buildActionReference(
      ActionRegistry([
        wipe(),
        echo(),
        _Typed(),
        FakeAction('ui_only', agentTool: false),
      ]),
    );
    String section(String name) {
      final start = text.indexOf('## $name');
      final end = text.indexOf('\n## ', start + 1);
      return text.substring(start, end < 0 ? text.length : end);
    }

    expect(section('echo'), contains('Flags: read-only'));
    expect(section('wipe'), contains('Flags: writes notes | needs approval'));
    expect(section('ui_only'), contains('Flags: writes notes | UI-only'));
    final add = section('add_item');
    expect(add, contains('Adds an item to the list.'));
    expect(add, contains('| `title` | string | yes | What to add. |'));
    expect(add, contains('| `count` | integer | no | How many. |'));
    expect(add, contains('| `tags` | array of string | no | Labels. |'));
    expect(add, contains('Failure codes: `duplicate`'));
    expect(section('echo'), isNot(contains('Failure codes')));
  });

  test('an action whose sample input cannot be built may need approval', () {
    final text = buildActionReference(ActionRegistry([BookAction()]));
    expect(text, contains('Flags: writes bookings | may need approval'));
  });

  test('an action without input says so', () {
    final text = buildActionReference(
      ActionRegistry([ViewScreenAction(AppContext(screens: const {}))]),
    );
    expect(text, contains('No input.'));
  });
}
